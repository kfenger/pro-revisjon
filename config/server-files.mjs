import { writeFile } from 'node:fs/promises';
import { securityHeaders, redirects, gonePaths, CANONICAL_HOST } from './server.mjs';

const htaccess = () => `# GENERATED by config/server-files.mjs – edit config/server.mjs instead.
# Apache (web hotel). Needs mod_rewrite and mod_headers, and only
# "AllowOverride FileInfo" – no Options/Indexes directives, so it also works on locked-down hosts.

AddDefaultCharset utf-8
AddType font/woff2 .woff2
AddType image/avif .avif
AddType image/webp .webp
AddType image/svg+xml .svg
AddType text/plain .txt

ErrorDocument 404 /404.html
ErrorDocument 403 /404.html
ErrorDocument 405 /404.html
ErrorDocument 410 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Static site: only GET and HEAD are meaningful.
  RewriteCond %{REQUEST_METHOD} !^(GET|HEAD)$
  RewriteRule ^ - [R=405,L]

  # Force HTTPS and the bare domain.
  RewriteCond %{HTTPS} !=on [OR]
  RewriteCond %{HTTP_HOST} !^${CANONICAL_HOST.replace(/\./g, '\\.')}$ [NC]
  RewriteRule ^ https://${CANONICAL_HOST}%{REQUEST_URI} [L,R=301,NE]

  # Hidden files (except .well-known) and host-specific config files are never served.
  RewriteRule (^|/)\\.(?!well-known/) - [R=404,L]
  RewriteRule ^_(headers|redirects)$ - [R=404,L]

  # No directory listings: a folder without index.html is a 404.
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteCond %{REQUEST_FILENAME}/index.html !-f
  RewriteRule ^ - [R=404,L]

  # Old WordPress pages that moved.
${redirects.map(([from, to]) => `  RewriteRule ^${from.replace(/^\/|\/$/g, '')}/?$ ${to} [L,R=301]`).join('\n')}

  # Old WordPress system paths are gone for good.
  RewriteRule ^(${gonePaths.map((p) => p.replace(/\./g, '\\.')).join('|')})(/.*)?$ - [G,L]
</IfModule>

<IfModule mod_headers.c>
${Object.entries(securityHeaders).map(([k, v]) => `  Header always set ${k} "${v}"`).join('\n')}
  Header always unset X-Powered-By

  # Everything in /_astro/ is content-hashed, so it can be cached forever.
  <FilesMatch "\\.(woff2|css|avif|webp|jpe?g)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <FilesMatch "\\.(svg|ico|png)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain application/xml image/svg+xml
</IfModule>
`;

const headers = () => `# GENERATED – edit config/server.mjs instead.
/*
${Object.entries(securityHeaders).map(([k, v]) => `  ${k}: ${v}`).join('\n')}

/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`;

const netlifyRedirects = () => `# GENERATED – edit config/server.mjs instead.
# Only 301s: Cloudflare Pages does not accept other codes here. Old WordPress paths simply return 404.
${redirects.flatMap(([from, to]) => [`${from.replace(/\/$/, '')}  ${to}  301`, `${from}  ${to}  301`]).join('\n')}
`;

export default function serverFiles() {
  return {
    name: 'server-files',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        await writeFile(new URL('.htaccess', dir), htaccess());
        await writeFile(new URL('_headers', dir), headers());
        await writeFile(new URL('_redirects', dir), netlifyRedirects());
      },
    },
  };
}
